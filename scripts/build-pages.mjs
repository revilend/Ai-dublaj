/**
 * Export a static build of the studio UI for GitHub Pages.
 *
 * GitHub Pages serves **static files only**, so it cannot host the FastAPI
 * backend (uvicorn/AI models/ffmpeg). What this produces is the real studio
 * interface — same template, same compiled Tailwind, same vendored JS — with:
 *
 *   • Jinja placeholders substituted for real values
 *   • root-absolute asset paths rewritten to relative ones (Pages serves a
 *     project site from `/<repo>/`, where `/static/...` would 404)
 *   • `window.VOX_API_BASE` injected, so the page talks to the hosted backend
 *     (the Hugging Face Space by default — override with the VOX_API_BASE env
 *     var when building)
 *
 * Run with:  npm run build:pages
 */

import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "pages");

//
// The published site has no backend of its own, so it ships pointing at the
// hosted Hugging Face Space. Set VOX_API_BASE (env, or the repository variable
// of the same name that pages.yml passes through) to target another backend,
// including `""` to render the honest "static preview" shell.
//
const DEFAULT_API_BASE = "https://revilend-ai-dublaj.hf.space";
const apiBase = String(process.env.VOX_API_BASE ?? DEFAULT_API_BASE).replace(/\/+$/, "");

/** Pull one string literal default out of app/core/config.py. */
function configDefault(field, fallback) {
  try {
    const source = readFileSync(join(root, "app", "core", "config.py"), "utf8");
    const match = source.match(new RegExp(`${field}\\s*:\\s*str\\s*=\\s*["']([^"']+)["']`));
    return match ? match[1] : fallback;
  } catch {
    return fallback;
  }
}

const appName = configDefault("app_name", "VoxStudio");
const appDescription = configDefault("app_description", "AI Voice Cloning & Video Dubbing Studio");

let version = "0.1.0";
try {
  version = JSON.parse(readFileSync(join(root, "package.json"), "utf8")).version || version;
} catch {
  /* keep the fallback */
}

// --------------------------------------------------------------------------- //
// Render the template
// --------------------------------------------------------------------------- //
let html = readFileSync(join(root, "app", "templates", "index.html"), "utf8");

const substitutions = {
  "{{ app_name }}": appName,
  "{{ app_description }}": appDescription,
  "{{ app_version }}": version,
};
for (const [token, value] of Object.entries(substitutions)) {
  html = html.split(token).join(value);
}

const leftover = html.match(/\{\{[^}]*\}\}|\{%[^%]*%\}/g);
if (leftover) {
  throw new Error(`Unsubstituted Jinja tokens remain: ${leftover.join(", ")}`);
}

// Relative assets so a project site under /<repo>/ resolves correctly.
html = html.replace(/(["'(])\/static\//g, "$1./static/");

// The API docs live on the backend, not on Pages.
html = html.replace(
  /href="\/docs"/g,
  apiBase ? `href="${apiBase}/docs"` : 'href="#" ',
);

// Inject the runtime configuration before any module runs.
const config = `<script>window.VOX_API_BASE = ${JSON.stringify(apiBase)};</script>\n`;
html = html.replace(/(\s*)(<script src="\.\/static\/js\/studio\.js")/, `$1${config}$1$2`);

// --------------------------------------------------------------------------- //
// Write the site
// --------------------------------------------------------------------------- //
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

writeFileSync(join(outDir, "index.html"), html, "utf8");
cpSync(join(root, "app", "static"), join(outDir, "static"), { recursive: true });

// Tell GitHub Pages not to run Jekyll over the output.
writeFileSync(join(outDir, ".nojekyll"), "", "utf8");

writeFileSync(
  join(outDir, "README.md"),
  [
    "# Static preview",
    "",
    "Generated by `npm run build:pages` — do not edit by hand.",
    "",
    apiBase
      ? `Backend: \`${apiBase}\``
      : "No backend configured (`VOX_API_BASE` is empty). The interface renders,",
    apiBase ? "" : "but every request will fail until an API host is set.",
    "",
  ].join("\n"),
  "utf8",
);

console.log(`Static site written to ${outDir}`);
console.log(`  app:    ${appName} v${version}`);
console.log(`  api:    ${apiBase || "(none — static preview only)"}`);
